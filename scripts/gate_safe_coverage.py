"""Owned gate cases for Verified Safe Coverage.

These cases are not generated by ``generate_cli_sweep.py``. They run the
sanitized Getnet-shaped fixture through the shared analysis seam and assert
verification, counts, and cross-Interface parity. All artifacts stay under
temporary directories and must not be committed.
"""

